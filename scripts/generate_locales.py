"""Generate compact UI and web dictionaries from the reviewed eight-language catalogs."""
from pathlib import Path
import json
ROOT=Path(__file__).resolve().parents[1]
def language_assets():
    languages=json.loads((ROOT/'resources/languages.json').read_text('utf-8'))
    codes=[row['code'] for row in languages]
    assert len(codes)==len(set(codes)) and codes==['zh','zh-TW','en','fr','de','ru','ja','ko'], 'Preserve persisted language indices'
    header='/* Generated by scripts/generate_locales.py. */\n#pragma once\n#define XTOUCH_LANGUAGE_COUNT_VALUE '+str(len(codes))+'\n#define XTOUCH_LANGUAGE_CODES '+','.join(json.dumps(c) for c in codes)+'\n'
    header=header.replace('#define XTOUCH_LANGUAGE_COUNT_VALUE', '#if XTOUCH_LANGUAGES_ZH_EN\n#define XTOUCH_LANGUAGE_COUNT_VALUE 3\n#define XTOUCH_LANGUAGE_CODES \"zh\",\"\",\"en\"\n#else\n#define XTOUCH_LANGUAGE_COUNT_VALUE')+'#endif\n'
    target=ROOT/'src/ui/i18n/language_metadata.h'
    if not target.exists() or target.read_text('utf-8')!=header:target.write_text(header,'utf-8')
    metadata='const languageMetadata='+json.dumps(languages,ensure_ascii=False,separators=(',',':'))+';\nconst languageCodes=languageMetadata.map(row=>row.code);\n'
    shared=metadata+(ROOT/'portal/language.js').read_text('utf-8')
    web=shared+"""
const websiteCodes=languageMetadata.filter(row=>row.website).map(row=>row.code);
const websiteLanguageKey='xTouch-CN.website.language';
function chineseWebsiteLanguage(value){return /^(?:zh|cmn|yue)(?:[-_]|$)/i.test(value||'');}
function websiteChoice(value){return chineseWebsiteLanguage(value)?'zh':value==='en'?'en':null;}
function websiteLanguage(){
  const explicit=websiteChoice(new URLSearchParams(location.search).get('lang'));
  if(explicit)return explicit;
  try {const saved=websiteChoice(localStorage.getItem(websiteLanguageKey));if(saved)return saved;} catch {}
  const preferred=navigator.languages?.[0]||navigator.language||'en';
  return chineseWebsiteLanguage(preferred)?'zh':'en';
}
function saveWebsiteLanguage(value){
  const chosen=websiteChoice(value);if(!chosen)return;
  try {localStorage.setItem(websiteLanguageKey,chosen);} catch {}
  const url=new URL(location.href);url.searchParams.set('lang',chosen);history.replaceState(null,'',url);
}
export {languageMetadata,languageCodes,websiteLanguage,saveWebsiteLanguage};
"""
    target=ROOT/'web/language.js'
    if not target.exists() or target.read_text('utf-8')!=web:target.write_text(web,'utf-8')
    return shared

def generate(limited=False):
    shared=language_assets()
    rows=json.loads((ROOT/'resources/ui-locales.json').read_text('utf-8'))
    assert all(len(v)==8 and v[2]==k and all(v) for k,v in rows.items())
    content='/* Generated by scripts/generate_locales.py. */\nstatic const char *const extraLocales[][8]={\n'
    content+=',\n'.join('    {'+','.join(json.dumps(x,ensure_ascii=False) for x in rows[k])+'}' for k in sorted(rows))+'\n};\n'
    target=ROOT/'src/ui/i18n/extra_locales.h'
    if not target.exists() or target.read_text('utf-8')!=content:target.write_text(content,'utf-8')
    portal=json.loads((ROOT/'resources/portal-locales.json').read_text('utf-8'))
    assert all(len(v)==8 and all(v) for v in portal.values())
    if limited:
        languages=[row for row in json.loads((ROOT/'resources/languages.json').read_text('utf-8')) if row['code'] in ('zh','en')]
        shared='const languageMetadata='+json.dumps(languages,ensure_ascii=False,separators=(',',':'))+';\nconst languageCodes=languageMetadata.map(row=>row.code);\n'+(ROOT/'portal/language.js').read_text('utf-8')
        portal={key:[values[0],values[2]] for key,values in portal.items()}
    return (shared+'const localeWords='+json.dumps(portal,ensure_ascii=False,separators=(',',':'))+';\n').encode('utf-8')
if __name__=='__main__':generate()
