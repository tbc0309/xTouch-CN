"""Generate optional print-file browser glyphs without enlarging standard fonts."""
import argparse,json,re,subprocess,sys
from pathlib import Path
from fontTools.ttLib import TTFont
ROOT=Path(__file__).resolve().parents[1]
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--font',type=Path,required=True);p.add_argument('--fallback-font',type=Path,required=True);p.add_argument('--converter',type=Path,required=True);a=p.parse_args()
# The library module only exports functions; invoke the executable entry point.
if a.converter.name=='cli.js' and (a.converter.parent.parent/'lv_font_conv.js').exists():
 a.converter=a.converter.parent.parent/'lv_font_conv.js'
source=(ROOT/'src/features/gcode_browser/view.cpp').read_text('utf8');source=source[source.index('const char *words'):source.index('lv_obj_t *overlay')]
values=[json.loads(x) for x in re.findall(r'"(?:\\.|[^"\\])*"',source)]
codes=set(range(32,127))|{ord(c) for text in values for c in text}|{0x2212,0xd7}
fonts=[a.font,a.fallback_font];maps=[TTFont(f).getBestCmap() for f in fonts];groups=[[],[]]
for code in sorted(codes):
 match=next((i for i,m in enumerate(maps) if code in m),None)
 if match is None:raise ValueError('Missing glyph '+hex(code))
 groups[match].append(code)
for size in (14,18,28):
 name='xtouch_files_font_'+str(size);target=ROOT/'src/features/gcode_browser'/('font_'+str(size)+'.c')
 command=['node',str(a.converter),'--size',str(size),'--bpp','4','--format','lvgl','--no-kerning','--lv-include','lvgl.h','--lv-font-name',name]
 for path,group in zip(fonts,groups):
  command+=['--font',str(path),'--symbols',''.join(chr(c) for c in group),'--autohint-strong']
 subprocess.run(command+['-o',str(target)],check=True)
 text=target.read_text('utf8');actual={int(x,16) for x in re.findall(r'/\* U\+([0-9A-Fa-f]+)',text)}
 missing=codes-actual
 if missing:raise RuntimeError('Generated font missing '+','.join(hex(c) for c in sorted(missing)))
 text=re.sub(r'^ \* Opts:.*$',' * Optional file-browser UI subset; generated by scripts/generate_file_browser_fonts.py.',text,flags=re.M);target.write_text(text,encoding='utf8')
 print(name,len(codes),'glyphs',flush=True)

# Keep the default filename profile in sync with translated UI captions.
subprocess.run([sys.executable,str(ROOT/"scripts/generate_filename_fonts.py"),"--font",str(a.font),"--fallback-font",str(a.fallback_font),"--converter",str(a.converter)],check=True)
