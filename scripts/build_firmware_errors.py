#!/usr/bin/env python3
"""Generate the firmware's flash-resident English printer error catalog."""
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "docs/data/error-codes.json"
OUTPUT = ROOT / "src/xtouch/error_descriptions.h"


def c_string(value: str) -> str:
    # JSON's escapes are valid C escapes for the content used in this catalog.
    return json.dumps(value, ensure_ascii=True)


def single_line_english(value: str) -> str:
    # Firmware details must not introduce line breaks or need a separate CJK font.
    punctuation = str.maketrans({"–": "-", "’": "'", "“": '"', "”": '"', "。": ".", "，": ","})
    return " ".join(value.translate(punctuation).split())


def main() -> None:
    source = json.loads(DATA.read_text(encoding="utf-8"))
    lines = [
        "/* Generated by scripts/build_firmware_errors.py; edit docs/data/error-codes.json. */",
        "#pragma once",
        "#include <stdint.h>",
        "typedef struct { uint64_t code; const char *en; } xtouch_error_description;",
    ]
    for category in ("hms", "device"):
        rows = sorted(source[category], key=lambda row: int(row[0], 16))
        codes = [row[0] for row in rows]
        if len(set(codes)) != len(codes):
            raise SystemExit(f"{category}: duplicate code in catalog")
        lines.append(f"static const xtouch_error_description {category}_descriptions[] = {{")
        for code, english in rows:
            english = single_line_english(english)
            if not english:
                raise SystemExit(f"{category} {code}: missing English description")
            lines.append(f"    {{ UINT64_C(0x{code}), {c_string(english)} }},")
        lines.append("};")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"Generated {OUTPUT.relative_to(ROOT)} ({sum(len(source[k]) for k in ('hms', 'device'))} records)")


if __name__ == "__main__":
    main()
