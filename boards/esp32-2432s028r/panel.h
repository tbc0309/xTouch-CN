#pragma once
#include <cstdint>
#include <initializer_list>

namespace XTouchCydPanel {
enum class Type { Ili9341, St7789 };
constexpr const char *name(Type type) {
    return type == Type::St7789 ? "st7789" : "ili9341-2";
}
constexpr bool inversion(Type type, bool userInvert) {
    return (type == Type::St7789) != userInvert;
}

// Both 240x320 panels use the same landscape DMA and touch coordinates.
// Keep controller power/gamma commands separate from the transport.
template<class Command, class Register, class Delay>
void initialize(Type type, Command command, Register reg, Delay pause) {
    if (type == Type::Ili9341) {
        command(0x01);
        pause(150);
        reg(0xcf, {0, 0xc1, 0x30});
        reg(0xed, {0x64, 3, 0x12, 0x81});
        reg(0xe8, {0x85, 0, 0x78});
        reg(0xcb, {0x39, 0x2c, 0, 0x34, 2});
        reg(0xf7, {0x20});
        reg(0xea, {0, 0});
        // Preserve the board's previously selected ILI9341_2 analog profile.
        // Panel-specific analog settings are applied through the native SPI driver.
        reg(0xc0, {0x10});
        reg(0xc1, {0x00});
        reg(0xc5, {0x30, 0x30});
        reg(0xc7, {0xb7});
        reg(0x36, {0x28});
        reg(0x3a, {0x55});
        reg(0xb1, {0, 0x1a});
        reg(0xb6, {8, 0x82, 0x27});
        reg(0xf2, {0});
        reg(0x26, {1});
        reg(0xe0, {0x0f, 0x2a, 0x28, 8, 0x0e, 8, 0x54, 0xa9, 0x43, 0x0a, 0x0f, 0, 0, 0, 0});
        reg(0xe1, {0, 0x15, 0x17, 7, 0x11, 6, 0x2b, 0x56, 0x3c, 5, 0x10, 0x0f, 0x3f, 0x3f, 0x0f});
        command(0x11);
        pause(120);
        command(0x29);
        return;
    }
    command(0x01);
    pause(150);
    command(0x11);
    pause(120);
    reg(0x36, {0x60}); // Landscape: exchange axes and mirror X; RGB order.
    reg(0x3a, {0x55}); // RGB565, high byte first on the shared SPI path.
    pause(10);
    reg(0xb2, {0x0c, 0x0c, 0x00, 0x33, 0x33});
    reg(0xb7, {0x35});
    reg(0xbb, {0x28});
    reg(0xc0, {0x0c});
    reg(0xc2, {0x01, 0xff});
    reg(0xc3, {0x10});
    reg(0xc4, {0x20});
    reg(0xc6, {0x0f});
    reg(0xd0, {0xa4, 0xa1});
    reg(0xe0, {0xd0, 0x00, 0x02, 0x07, 0x0a, 0x28, 0x32, 0x44, 0x42, 0x06, 0x0e, 0x12, 0x14, 0x17});
    reg(0xe1, {0xd0, 0x00, 0x02, 0x07, 0x0a, 0x28, 0x31, 0x54, 0x47, 0x0e, 0x1c, 0x17, 0x1b, 0x1e});
    command(0x21); // This panel's normal colors require display inversion.
    command(0x13);
    pause(10);
    command(0x29);
    pause(120);
}
} // namespace XTouchCydPanel
